CREATE TABLE IF NOT EXISTS work_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(200) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','EMPLOYEE','APPROVER','EXECUTOR'))
);
CREATE TABLE IF NOT EXISTS flow_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(140) NOT NULL,
    draft_json CLOB NOT NULL,
    draft_revision INT NOT NULL DEFAULT 0,
    published_version INT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS flow_version (
    template_id BIGINT NOT NULL REFERENCES flow_template(id),
    number INT NOT NULL CHECK (number > 0),
    definition_json CLOB NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_by BIGINT NOT NULL REFERENCES work_account(id),
    PRIMARY KEY (template_id, number)
);
CREATE TABLE IF NOT EXISTS flow_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL,
    template_version INT NOT NULL,
    creator_id BIGINT NOT NULL REFERENCES work_account(id),
    payload_json CLOB NOT NULL,
    state VARCHAR(20) NOT NULL CHECK (state IN ('ACTIVE','COMPLETED','REJECTED')),
    current_step INT,
    assigned_person BIGINT REFERENCES work_account(id),
    assigned_role VARCHAR(20),
    due_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (template_id, template_version) REFERENCES flow_version(template_id, number),
    CHECK ((state = 'ACTIVE' AND current_step IS NOT NULL AND due_at IS NOT NULL
            AND ((assigned_person IS NULL AND assigned_role IS NOT NULL) OR (assigned_person IS NOT NULL AND assigned_role IS NULL)))
        OR (state <> 'ACTIVE' AND current_step IS NULL AND assigned_person IS NULL AND assigned_role IS NULL AND due_at IS NULL))
);
CREATE INDEX IF NOT EXISTS flow_run_creator ON flow_run (creator_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS flow_run_person ON flow_run (state, assigned_person, due_at);
CREATE INDEX IF NOT EXISTS flow_run_role ON flow_run (state, assigned_role, due_at);
CREATE TABLE IF NOT EXISTS flow_launch (
    nonce UUID PRIMARY KEY,
    creator_id BIGINT NOT NULL REFERENCES work_account(id),
    template_id BIGINT NOT NULL,
    template_version INT NOT NULL,
    run_id BIGINT UNIQUE REFERENCES flow_run(id),
    payload_hash CHAR(64),
    FOREIGN KEY (template_id, template_version) REFERENCES flow_version(template_id, number),
    CHECK ((run_id IS NULL AND payload_hash IS NULL) OR (run_id IS NOT NULL AND payload_hash IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS flow_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES flow_run(id),
    action VARCHAR(20) NOT NULL CHECK (action IN ('START','APPROVE','REJECT','COMPLETE')),
    step_name VARCHAR(140),
    actor_id BIGINT NOT NULL REFERENCES work_account(id),
    note VARCHAR(1000) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS flow_event_run ON flow_event (run_id, id);
CREATE INDEX IF NOT EXISTS flow_event_actor ON flow_event (actor_id, run_id);

CREATE TABLE IF NOT EXISTS flow_demo_scenario (
    scenario_key VARCHAR(80) PRIMARY KEY
);
